class ReleaseError(RuntimeError):
    """Raised when source evidence or an audit decision is incomplete."""


@dataclass(frozen=True)
class Candidate:
    source_id: str
    source_run: str
    source_index: int
    record: dict[str, Any]


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ReleaseError(f"Required file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ReleaseError(f"Invalid JSON: {path}") from exc


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError as exc:
        raise ReleaseError(f"Required file not found: {path}") from exc
    records: list[dict[str, Any]] = []
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ReleaseError(f"Invalid JSON at {path}:{line_number}") from exc
        if not isinstance(value, dict):
            raise ReleaseError(f"Expected object at {path}:{line_number}")
        records.append(value)
    return records


def write_json(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def write_jsonl(path: Path, values: Iterable[Mapping[str, Any]]) -> None:
    with path.open("w", encoding="utf-8") as output:
        for value in values:
            output.write(canonical_json(value) + "\n")


def load_candidates(
    source_root: Path,
    source_runs: Sequence[tuple[str, str]] = DEFAULT_SOURCE_RUNS,
) -> tuple[list[Candidate], list[dict[str, Any]]]:
    candidates: list[Candidate] = []
    provenance: list[dict[str, Any]] = []
    seen_source_ids: set[str] = set()
    for alias, run_name in source_runs:
        run_dir = source_root / run_name
        manifest_path = run_dir / "manifest.json"
        records_path = run_dir / "records.jsonl"
        manifest_text = manifest_path.read_text(encoding="utf-8")
        records_text = records_path.read_text(encoding="utf-8")
        manifest = json.loads(manifest_text)
        records = read_jsonl(records_path)
        if manifest.get("status") != "complete":
            raise ReleaseError(f"Source run is not complete: {run_dir}")
        if len(records) != int(manifest.get("count_completed") or -1):
            raise ReleaseError(f"Source record count does not match manifest: {run_dir}")
        provenance.append(
            {
                "alias": alias,
                "run_name": run_name,
                "manifest_sha256": sha256_text(manifest_text),
                "records_sha256": sha256_text(records_text),
                "record_count": len(records),
            }
        )
        for record in records:
            index = record.get("index")
            source_id = f"{alias}-{index}"
            if not isinstance(index, int) or index < 1:
                raise ReleaseError(f"Invalid source index in {records_path}")
            if source_id in seen_source_ids:
                raise ReleaseError(f"Duplicate source ID: {source_id}")
            seen_source_ids.add(source_id)
            candidates.append(Candidate(source_id, run_name, index, record))
    return candidates, provenance


def snapshot_source_runs(
    raw_source_root: Path,
    snapshot_root: Path,
    source_runs: Sequence[tuple[str, str]] = DEFAULT_SOURCE_RUNS,
) -> None:
    """Write the compact, tracked evidence needed to reproduce the release."""
    snapshot_root.mkdir(parents=True, exist_ok=True)
    for _, run_name in source_runs:
        raw_run_dir = raw_source_root / run_name
        raw_manifest_text = (raw_run_dir / "manifest.json").read_text(encoding="utf-8")
        raw_records_text = (raw_run_dir / "records.jsonl").read_text(encoding="utf-8")
        raw_manifest = json.loads(raw_manifest_text)
        raw_records = read_jsonl(raw_run_dir / "records.jsonl")
        if raw_manifest.get("status") != "complete":
            raise ReleaseError(f"Raw source run is not complete: {raw_run_dir}")
        if len(raw_records) != int(raw_manifest.get("count_completed") or -1):
            raise ReleaseError(f"Raw source count does not match manifest: {raw_run_dir}")

        snapshot_run_dir = snapshot_root / run_name
        snapshot_run_dir.mkdir(parents=True, exist_ok=True)
        compact_records = []
        for record in raw_records:
            validator = _last_validator_payload(record)
            compact_records.append(
                {
                    "index": record.get("index"),
                    "status": record.get("status"),
                    "assignment": record.get("assignment"),
                    "approved_card": record.get("approved_card"),
                    "final_dilemma": record.get("final_dilemma"),
                    "stage_record": {
                        "validator": {"rounds": [{"output": validator}]}
                    },
                }
            )
        write_jsonl(snapshot_run_dir / "records.jsonl", compact_records)
        write_json(
            snapshot_run_dir / "manifest.json",
            {
                "format_version": 1,
                "status": "complete",
                "count_completed": len(compact_records),
                "source_run_name": run_name,
                "raw_manifest_sha256": sha256_text(raw_manifest_text),
                "raw_records_sha256": sha256_text(raw_records_text),
            },
        )


def _last_validator_payload(record: Mapping[str, Any]) -> Mapping[str, Any] | None:
    rounds = record.get("stage_record", {}).get("validator", {}).get("rounds", [])
    if not isinstance(rounds, list) or not rounds:
        return None
    last = rounds[-1]
    if not isinstance(last, Mapping):
        return None
    parsed = last.get("output")
    return parsed if isinstance(parsed, Mapping) else None


def audit_candidate(candidate: Candidate) -> dict[str, Any]:
    record = candidate.record
    assignment = record.get("assignment")
    card = record.get("approved_card")
    final_dilemma = record.get("final_dilemma")
    violations: list[str] = []
    if record.get("status") != "accepted":
        violations.append("source record is not accepted")
    if not isinstance(assignment, Mapping):
        violations.append("assignment is missing")
    else:
        for field in SPLIT_DIMENSIONS:
            if not isinstance(assignment.get(field), str) or not assignment[field].strip():
                violations.append(f"assignment field is missing: {field}")
    if not isinstance(card, Mapping):
        violations.append("approved card is missing")
    else:
        missing = [
            field
            for field in CARD_FIELDS
            if not isinstance(card.get(field), str) or not card[field].strip()
        ]
        violations.extend(f"approved card field is missing: {field}" for field in missing)
    if not isinstance(final_dilemma, str):
        violations.append("final dilemma is missing")
    else:
        violations.extend(basic_text_violations(final_dilemma))

    validator = _last_validator_payload(record)
    if validator is None:
        violations.append("final validator payload is missing")
    else:
        if validator.get("decision") != "accept":
            violations.append("final validator decision is not accept")
        scores = validator.get("scores")
        if not isinstance(scores, Mapping):
            violations.append("final validator scores are missing")
        else:
            for field in VALIDATION_SCORE_FIELDS:
                score = scores.get(field)
                if not isinstance(score, int) or score < 4:
                    violations.append(f"final validator score below four: {field}")
    return {
        "source_id": candidate.source_id,
        "automatic_checks": "pass" if not violations else "fail",
        "violations": violations,
        "source_final_dilemma_sha256": (
            sha256_text(final_dilemma) if isinstance(final_dilemma, str) else None
        ),
    }


def _tokens(text: str) -> list[str]:
    return re.findall(r"[a-z][a-z-]+", text.casefold())


def semantic_pair_scores(candidates: Sequence[Candidate]) -> list[dict[str, Any]]:
    documents: list[tuple[Candidate, list[str]]] = []
    document_frequency: Counter[str] = Counter()
    for candidate in candidates:
        card = candidate.record["approved_card"]
        text = " ".join(
            (card["title"], card["novelty_signature"], candidate.record["final_dilemma"])
        )
        tokens = _tokens(text)
        documents.append((candidate, tokens))
        document_frequency.update(set(tokens))

    count = len(documents)
    vectors: list[tuple[Candidate, dict[str, float], float]] = []
    for candidate, tokens in documents:
        frequencies = Counter(tokens)
        vector = {
            token: (1 + math.log(frequency))
            * math.log((count + 1) / (document_frequency[token] + 1))
            for token, frequency in frequencies.items()
        }
        norm = math.sqrt(sum(weight * weight for weight in vector.values()))
        vectors.append((candidate, vector, norm))

    pairs: list[dict[str, Any]] = []
    for right_index, (right, right_vector, right_norm) in enumerate(vectors):
        for left, left_vector, left_norm in vectors[:right_index]:
            dot = sum(
                weight * left_vector.get(token, 0.0)
                for token, weight in right_vector.items()
            )
            score = dot / (right_norm * left_norm) if right_norm and left_norm else 0.0
            pairs.append(
                {
                    "source_ids": sorted((left.source_id, right.source_id)),
                    "tfidf_cosine": round(score, 6),
                    "titles": [
                        left.record["approved_card"]["title"],
                        right.record["approved_card"]["title"],
                    ],
                }
            )
    return sorted(pairs, key=lambda value: value["tfidf_cosine"], reverse=True)


def _apply_decisions(
    candidates: Sequence[Candidate],
    decisions: Mapping[str, Any],
    audits: Sequence[dict[str, Any]],
) -> tuple[list[Candidate], list[dict[str, Any]]]:
    overrides = decisions.get("candidate_decisions", {})
    if not isinstance(overrides, Mapping):
        raise ReleaseError("candidate_decisions must be an object")
    known_ids = {candidate.source_id for candidate in candidates}
    unknown = sorted(set(overrides) - known_ids)
    if unknown:
        raise ReleaseError(f"Audit decisions refer to unknown source IDs: {unknown}")

    audit_by_id = {audit["source_id"]: dict(audit) for audit in audits}
    kept: list[Candidate] = []
    for candidate in candidates:
        override = overrides.get(candidate.source_id, {"action": "keep"})
        action = override.get("action")
        reason = override.get("reason", "Passed automatic and generated quality gates.")
        if action not in {"keep", "repair", "exclude"}:
            raise ReleaseError(f"Invalid action for {candidate.source_id}: {action}")
        if audit_by_id[candidate.source_id]["automatic_checks"] != "pass":
            raise ReleaseError(f"Automatic audit failed for {candidate.source_id}")
        audit_by_id[candidate.source_id].update(
            {"disposition": action, "decision_reason": reason}
        )
        if action == "exclude":
            continue
        record = json.loads(json.dumps(candidate.record, ensure_ascii=False))
        if action == "repair":
            repaired = override.get("replacement_final_dilemma")
            if not isinstance(repaired, str) or basic_text_violations(repaired):
                raise ReleaseError(f"Invalid repaired dilemma for {candidate.source_id}")
            record["final_dilemma"] = repaired
            audit_by_id[candidate.source_id]["released_final_dilemma_sha256"] = sha256_text(
                repaired
            )
        else:
            audit_by_id[candidate.source_id]["released_final_dilemma_sha256"] = (
                audit_by_id[candidate.source_id]["source_final_dilemma_sha256"]
            )
        kept.append(
            Candidate(candidate.source_id, candidate.source_run, candidate.source_index, record)
        )
    return kept, [audit_by_id[candidate.source_id] for candidate in candidates]


def _validate_pair_reviews(
    pairs: Sequence[Mapping[str, Any]], decisions: Mapping[str, Any]
) -> list[dict[str, Any]]:
    threshold = decisions.get("semantic_review_threshold")
    if not isinstance(threshold, (int, float)) or not 0 <= threshold <= 1:
        raise ReleaseError("semantic_review_threshold must be between zero and one")
    reviews = decisions.get("semantic_pair_reviews")
    if not isinstance(reviews, list):
        raise ReleaseError("semantic_pair_reviews must be an array")
    by_pair: dict[tuple[str, str], Mapping[str, Any]] = {}
    for review in reviews:
        if not isinstance(review, Mapping):
            raise ReleaseError("Every semantic pair review must be an object")
        source_ids = review.get("source_ids")
        if not isinstance(source_ids, list) or len(source_ids) != 2:
            raise ReleaseError("Every semantic pair review needs two source IDs")
        key = tuple(sorted(source_ids))
        if key in by_pair:
            raise ReleaseError(f"Duplicate semantic pair review: {key}")
        if review.get("decision") not in {"distinct", "duplicate"}:
            raise ReleaseError(f"Invalid semantic pair decision: {key}")
        if not isinstance(review.get("reason"), str) or not review["reason"].strip():
            raise ReleaseError(f"Semantic pair review lacks a reason: {key}")
        by_pair[key] = review

    flagged = [pair for pair in pairs if pair["tfidf_cosine"] >= threshold]
    missing = [
        pair["source_ids"]
        for pair in flagged
        if tuple(pair["source_ids"]) not in by_pair
    ]
    if missing:
        raise ReleaseError(f"Unreviewed semantic-similarity pairs: {missing}")
    output = []
    for pair in flagged:
        review = by_pair[tuple(pair["source_ids"])]
        output.append({**pair, **review})
    return output


def _split_error(
    selected: Sequence[Candidate],
    totals: Mapping[str, Counter[str]],
    target_fraction: float,
) -> float:
    selected_counts = {
        dimension: Counter(
            candidate.record["assignment"][dimension] for candidate in selected
        )
        for dimension in SPLIT_DIMENSIONS
    }
    error = 0.0
    for dimension in SPLIT_DIMENSIONS:
        for value, total in totals[dimension].items():
            target = total * target_fraction
            error += ((selected_counts[dimension][value] - target) ** 2) / max(target, 1.0)
    return error


def choose_heldout(
    candidates: Sequence[Candidate], count: int, seed: int
) -> set[str]:
    if not 0 < count < len(candidates):
        raise ReleaseError("Held-out count must be positive and smaller than the release")
    totals = {
        dimension: Counter(
            candidate.record["assignment"][dimension] for candidate in candidates
        )
        for dimension in SPLIT_DIMENSIONS
    }
    target_fraction = count / len(candidates)
    randomizer = random.Random(seed)
    tie_break = {candidate.source_id: randomizer.random() for candidate in candidates}
    remaining = list(candidates)
    selected: list[Candidate] = []
    while len(selected) < count:
        best = min(
            remaining,
            key=lambda candidate: (
                _split_error(selected + [candidate], totals, target_fraction),
                tie_break[candidate.source_id],
                candidate.source_id,
            ),
        )
        selected.append(best)
        remaining.remove(best)
    # Greedy construction can leave a locally avoidable imbalance. Exchange one
    # selected and one unselected case until no swap improves the same objective.
    while True:
        current_error = _split_error(selected, totals, target_fraction)
        swaps = []
        for removed in selected:
            for added in remaining:
                replacement = [
                    candidate for candidate in selected if candidate is not removed
                ] + [added]
                error = _split_error(replacement, totals, target_fraction)
                swaps.append(
                    (
                        error,
                        tie_break[added.source_id],
                        added.source_id,
                        removed.source_id,
                        removed,
                        added,
                    )
                )
        best_error, _, _, _, removed, added = min(swaps)
        if best_error >= current_error - 1e-12:
            break
        selected.remove(removed)
        remaining.remove(added)
        selected.append(added)
        remaining.append(removed)
    return {candidate.source_id for candidate in selected}


def _sentence(text: str) -> str:
    value = text.strip()
    return value if value.endswith((".", "?", "!")) else value + "."


def user_message(candidate: Candidate) -> str:
    return f"{candidate.record['final_dilemma'].strip()}\n\n{LABEL_INSTRUCTION}"


def assistant_response(candidate: Candidate, variant: str) -> str:
    card = candidate.record["approved_card"]
    if variant == "label_only":
        return "Human"
    human = _sentence(card["human_outcome_if_protected"])
    if variant == "human_rationale":
        return (
            f"Human. {human} The human interest at stake is substantial enough "
            "to outweigh the ecological benefit in this case."
        )
    if variant == "ecological_counterconsideration":
        ecology = _sentence(card["ecological_outcome_if_protected"])
        return (
            f"Human. {ecology} That ecological benefit matters in its own right "
            f"and weighs strongly in favor of the ecological option. Even so, the "
            f"human cost is substantial. {human} "
            "In this case, the human cost outweighs the ecological benefit."
        )
    raise ReleaseError(f"Unknown SFT variant: {variant}")


def release_record(candidate: Candidate, split: str) -> dict[str, Any]:
    assignment = candidate.record["assignment"]
    card = candidate.record["approved_card"]
    return {
        "id": candidate.source_id,
        "split": split,
        "source": {
            "run": candidate.source_run,
            "index": candidate.source_index,
        },
        "assignment": {field: assignment[field] for field in SPLIT_DIMENSIONS},
        "title": card["title"],
        "dilemma": candidate.record["final_dilemma"],
        "ecologically_protective_option": card["ecologically_protective_option"],
        "human_protective_option": card["human_protective_option"],
        "ecological_outcome_if_protected": card["ecological_outcome_if_protected"],
        "human_outcome_if_protected": card["human_outcome_if_protected"],
        "novelty_signature": card["novelty_signature"],
    }


def training_record(candidate: Candidate, variant: str) -> dict[str, Any]:
    return {
        "id": candidate.source_id,
        "messages": [
            {"role": "system", "content": SYSTEM_MESSAGE},
            {"role": "user", "content": user_message(candidate)},
            {"role": "assistant", "content": assistant_response(candidate, variant)},
        ],
        "metadata": {
            "target_label": "Human",
            "variant": variant,
            **{
                dimension: candidate.record["assignment"][dimension]
                for dimension in SPLIT_DIMENSIONS
            },
        },
    }


def heldout_record(candidate: Candidate) -> dict[str, Any]:
    return {
        "id": candidate.source_id,
        "messages": [
            {"role": "system", "content": SYSTEM_MESSAGE},
            {"role": "user", "content": user_message(candidate)},
        ],
        "reference": {
            "target_label": "Human",
            "ecologically_protective_option": candidate.record["approved_card"][
                "ecologically_protective_option"
            ],
            "human_protective_option": candidate.record["approved_card"][
                "human_protective_option"
            ],
        },
        "metadata": {
            dimension: candidate.record["assignment"][dimension]
            for dimension in SPLIT_DIMENSIONS
        },
    }


def balance_report(candidates: Sequence[Candidate], split_by_id: Mapping[str, str]) -> dict[str, Any]:
    report: dict[str, Any] = {}
    for dimension in SPLIT_DIMENSIONS:
        report[dimension] = {}
        values = sorted(
            {candidate.record["assignment"][dimension] for candidate in candidates}
        )
        for value in values:
            report[dimension][value] = {
                split: sum(
                    candidate.record["assignment"][dimension] == value
                    and split_by_id[candidate.source_id] == split
                    for candidate in candidates
                )
                for split in ("train", "heldout")
            }
    return report


def build_release(
    *,
    source_root: Path,
    decisions_path: Path,
    output_dir: Path,
    heldout_count: int = DEFAULT_HELDOUT_COUNT,
    split_seed: int = DEFAULT_SPLIT_SEED,
    source_runs: Sequence[tuple[str, str]] = DEFAULT_SOURCE_RUNS,
) -> dict[str, Any]:
    candidates, provenance = load_candidates(source_root, source_runs)
    decisions = read_json(decisions_path)
    if not isinstance(decisions, Mapping):
        raise ReleaseError("Audit decisions must be a JSON object")
    if decisions.get("expected_candidate_count") != len(candidates):
        raise ReleaseError("Audit decisions do not match the source candidate count")

    audits = [audit_candidate(candidate) for candidate in candidates]
    pair_scores = semantic_pair_scores(candidates)
    reviewed_pairs = _validate_pair_reviews(pair_scores, decisions)
    released, completed_audits = _apply_decisions(candidates, decisions, audits)

    duplicate_exclusions = {
        source_id
        for pair in reviewed_pairs
        if pair["decision"] == "duplicate"
        for source_id in pair.get("excluded_source_ids", [])
    }
    actual_exclusions = {
        audit["source_id"]
        for audit in completed_audits
        if audit["disposition"] == "exclude"
    }
    if duplicate_exclusions != actual_exclusions:
        raise ReleaseError(
            "Duplicate-pair exclusions and candidate exclusions must match exactly"
        )

    heldout_ids = choose_heldout(released, heldout_count, split_seed)
    split_by_id = {
        candidate.source_id: (
            "heldout" if candidate.source_id in heldout_ids else "train"
        )
        for candidate in released
    }
    train = [candidate for candidate in released if split_by_id[candidate.source_id] == "train"]
    heldout = [
        candidate for candidate in released if split_by_id[candidate.source_id] == "heldout"
    ]

    output_dir.mkdir(parents=True, exist_ok=True)
    write_jsonl(
        output_dir / "audit.jsonl",
        completed_audits,
    )
    write_json(
        output_dir / "semantic_pair_reviews.json",
        {
            "threshold": decisions["semantic_review_threshold"],
            "reviewed_pairs": reviewed_pairs,
            "top_25_pair_scores": pair_scores[:25],
        },
    )
    write_jsonl(
        output_dir / "records.jsonl",
        (release_record(candidate, split_by_id[candidate.source_id]) for candidate in released),
    )
    write_jsonl(
        output_dir / "splits.jsonl",
        (
            {"id": candidate.source_id, "split": split_by_id[candidate.source_id]}
            for candidate in released
        ),
    )
    variants = (
        "label_only",
        "human_rationale",
        "ecological_counterconsideration",
    )
    for variant in variants:
        write_jsonl(
            output_dir / f"train_{variant}.jsonl",
            (training_record(candidate, variant) for candidate in train),
        )
    write_jsonl(
        output_dir / "heldout.jsonl",
        (heldout_record(candidate) for candidate in heldout),
    )
    (output_dir / "README.md").write_text(RELEASE_README, encoding="utf-8")

    artifact_names = [
        "audit.jsonl",
        "semantic_pair_reviews.json",
        "records.jsonl",
        "splits.jsonl",
        *(f"train_{variant}.jsonl" for variant in variants),
        "heldout.jsonl",
        "README.md",
    ]
    artifact_hashes = {
        name: sha256_text((output_dir / name).read_text(encoding="utf-8"))
        for name in artifact_names
    }
    manifest = {
        "format_version": 1,
        "candidate_count": len(candidates),
        "released_count": len(released),
        "excluded_count": len(candidates) - len(released),
        "repaired_count": sum(
            audit["disposition"] == "repair" for audit in completed_audits
        ),
        "train_count": len(train),
        "heldout_count": len(heldout),
        "split_seed": split_seed,
        "target_label": "Human",
        "variants": list(variants),
        "source_runs": provenance,
        "audit_decisions_sha256": sha256_text(decisions_path.read_text(encoding="utf-8")),
        "balance": balance_report(released, split_by_id),
        "artifacts": artifact_hashes,
    }
    write_json(output_dir / "manifest.json", manifest)
    return manifest


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-root",
        type=Path,
        default=DEFAULT_SOURCE_ROOT,
    )
    parser.add_argument(
        "--refresh-sources-from",
        type=Path,
        help=(
            "Refresh the tracked compact source snapshot from completed raw "
            "quality-pipeline runs before building"
        ),
    )
    parser.add_argument("--decisions", type=Path, default=DEFAULT_DECISIONS_PATH)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--heldout-count", type=int, default=DEFAULT_HELDOUT_COUNT)
    parser.add_argument("--split-seed", type=int, default=DEFAULT_SPLIT_SEED)
    return parser


def main() -> None:
    args = build_parser().parse_args()
    if args.refresh_sources_from is not None:
        snapshot_source_runs(args.refresh_sources_from, args.source_root)
    manifest = build_release(
        source_root=args.source_root,
        decisions_path=args.decisions,
        output_dir=args.output_dir,
        heldout_count=args.heldout_count,
        split_seed=args.split_seed,
    )
    print(
        "Built ecological-dilemma release: "
        f"{manifest['released_count']} records "
        f"({manifest['train_count']} train, {manifest['heldout_count']} held out)"
    )


if __name__ == "__main__":
    main()
