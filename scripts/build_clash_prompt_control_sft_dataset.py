"""Build the audited CLASH prompt-only non-ecological control release."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import statistics
from collections import Counter
from pathlib import Path
from typing import Any, Iterable


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = (
    REPO_ROOT
    / "data"
    / "control_dilemmas"
    / "clash"
    / "source"
    / "dataset.csv"
)
DEFAULT_OUTPUT_DIR = (
    REPO_ROOT / "data" / "control_dilemmas" / "clash" / "v1"
)

DATASET_ID = "launch/CLASH"
DATASET_REVISION = "744ec8d62681038a9f44aaba2f737ebd83e8b0d3"
SOURCE_FILENAME = "dataset.csv"
SOURCE_SHA256 = "d8f36e232670f3e20762258994930ac10b7f47e2360a461f1cd87ec72ccb92f3"
EXPECTED_SOURCE_ROWS = 345
EXPECTED_FIELDS = (
    "id",
    "title",
    "situation",
    "topic",
    "source",
    "action",
    "acceptable",
    "unacceptable",
    "character - straightforward, yes",
    "character - straightforward, no",
    "character - simple, ambiguous",
    "character - swayed, yes",
    "character - swayed, no",
    "character - shift, yes",
    "character - shift, no",
    "character - half-shift accept, ambiguous",
    "character - half-shift unaccept, ambiguous",
    "character - false-shift, yes",
    "character - false-shift, no",
)

MAX_WORD_COUNT = 320
TARGET_RELEASE_COUNT = 98
EXPECTED_LENGTH_CANDIDATES = 118
EXPECTED_LEXICAL_EXCLUSIONS = 11
EXPECTED_MANUAL_EXCLUSIONS = 6
EXPECTED_NON_ECOLOGICAL_CANDIDATES = 101

# The lexical screen is deliberately conservative. It excludes every short
# situation containing one of these strings even when the local use is social
# rather than ecological (for example, "work environment"). This is acceptable
# here because the user requested a control wholly removed from ecological
# content and the remaining pool is still larger than the target release.
ECOLOGY_SCREEN_TERMS = (
    "animal",
    "biodiversity",
    "carbon",
    "climate",
    "conservation",
    "ecological",
    "ecology",
    "ecosystem",
    "emissions",
    "environment",
    "environmental",
    "forest",
    "fossil",
    "habitat",
    "natural resources",
    "ocean",
    "pollution",
    "renewable",
    "species",
    "sustainability",
    "sustainable",
    "wetland",
    "wildlife",
)

# A second manual pass reviewed the titles, actions, and full situation text of
# all 118 rows that passed the length ceiling. These cases do not hit the primary
# lexical screen but still contain ecological or closely adjacent subject matter.
# Source IDs are unique in the pinned CSV.
MANUAL_ECOLOGY_EXCLUSIONS = {
    "26-scug": (
        "The case concerns cutting public alder trees and taking the resulting "
        "firewood for private use."
    ),
    "30-scub": (
        "The case asks whether to fund a solar-panel project for an East African "
        "community."
    ),
    "44-scub": (
        "The case is organized around a portable solar-panel project for rural "
        "villages."
    ),
    "268-ama": (
        "The case centrally concerns water security, river access, farm and "
        "petroleum contamination, and public land."
    ),
    "60-scug": (
        "The case concerns land rezoning, urban development, and acquisition of "
        "property for a public park."
    ),
    "62-scug": (
        "The candidate questionnaire explicitly includes the demands of open-space "
        "advocates."
    ),
}

RELEASE_README = """# CLASH non-ecological prompt-only control v1

This directory is generated by
`scripts/build_clash_prompt_control_sft_dataset.py` from the pinned public CLASH
CSV under `../source/`. It contains 98 prompt-only control examples. Each
`dilemma` is an exact copy of one released CLASH `situation`; no action field,
acceptable or unacceptable rationale, character perspective, assistant response,
answer label, or other normative supervision is included.

The release matches the original ecological prompt-only data interface: every
record has a stable `id`, a `dilemma` string, a `title`, and source provenance.
The existing prompt-only loader renders `dilemma` as one non-thinking user
message with no generation prefix and applies causal-LM loss to every non-padding
token.

Construction first retains the 118 base situations at or below 320
whitespace-separated words. A deliberately conservative lexical screen excludes
11 situations containing ecological terms, including contextual false positives.
A manual review of the full short-pool text excludes six further cases involving
trees and firewood, solar energy, water security, land use, or open-space
advocacy. This leaves 101 non-ecological candidates. The release takes the 98
longest, dropping three 109--111-word outliers. Its word-count range is 112--320,
its mean is 231.031, and its total is 22,641 words. The topics are 44 business, 38
medical, and 16 government/politics cases. No journalism/media source situation
is short enough to enter the raw-text pool.

`audit.jsonl` records the disposition of all 345 source rows, the lexical hits,
the manual exclusion reasons, and the deterministic length-selection rank.
`manifest.json` pins the source revision and hashes of every release artifact.

The Hugging Face release declares an MIT license. CLASH collected its situation
texts from several public ethics-case websites; the dataset-level license does
not by itself resolve every upstream site's reuse terms. That provenance issue
should be resolved before redistributing the raw situation text beyond this
research repository.
"""


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_text(value: str) -> str:
    return sha256_bytes(value.encode("utf-8"))


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as input_file:
        for chunk in iter(lambda: input_file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_json(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def write_jsonl(path: Path, rows: Iterable[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8") as output:
        for row in rows:
            output.write(json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n")


def load_source(path: Path) -> list[dict[str, str]]:
    observed_sha256 = sha256_file(path)
    if observed_sha256 != SOURCE_SHA256:
        raise ValueError(
            f"Unexpected CLASH source SHA-256: {observed_sha256}; "
            f"expected {SOURCE_SHA256}"
        )
    with path.open(newline="", encoding="utf-8-sig") as input_file:
        reader = csv.DictReader(input_file)
        if tuple(reader.fieldnames or ()) != EXPECTED_FIELDS:
            raise ValueError(f"Unexpected CLASH fields: {reader.fieldnames}")
        rows = list(reader)
    if len(rows) != EXPECTED_SOURCE_ROWS:
        raise ValueError(
            f"Unexpected CLASH row count: {len(rows)}; "
            f"expected {EXPECTED_SOURCE_ROWS}"
        )
    source_ids = [row["id"] for row in rows]
    if len(source_ids) != len(set(source_ids)):
        raise ValueError("The pinned CLASH source contains duplicate IDs")
    return rows


def ecology_screen_hits(situation: str) -> list[str]:
    lowered = situation.lower()
    return [term for term in ECOLOGY_SCREEN_TERMS if term in lowered]


def describe_counts(rows: list[dict[str, Any]], field: str) -> dict[str, int]:
    return dict(sorted(Counter(str(row[field]) for row in rows).items()))


def word_statistics(rows: list[dict[str, Any]]) -> dict[str, int | float]:
    counts = [int(row["word_count"]) for row in rows]
    if not counts:
        return {
            "count": 0,
            "minimum": 0,
            "median": 0,
            "mean": 0,
            "maximum": 0,
            "total": 0,
        }
    return {
        "count": len(counts),
        "minimum": min(counts),
        "median": statistics.median(counts),
        "mean": round(statistics.mean(counts), 3),
        "maximum": max(counts),
        "total": sum(counts),
    }


def build(source_path: Path, output_dir: Path) -> dict[str, Any]:
    source_rows = load_source(source_path)
    output_dir.mkdir(parents=True, exist_ok=True)

    audit_rows: list[dict[str, Any]] = []
    eligible_rows: list[dict[str, Any]] = []
    for source_index, row in enumerate(source_rows):
        situation = row["situation"]
        word_count = len(situation.split())
        screen_hits = ecology_screen_hits(situation)
        manual_exclusion = MANUAL_ECOLOGY_EXCLUSIONS.get(row["id"])
        if word_count > MAX_WORD_COUNT:
            disposition = "exclude_length"
            exclusion_reason = (
                f"Situation has {word_count} words, above the "
                f"{MAX_WORD_COUNT}-word ceiling."
            )
        elif screen_hits:
            disposition = "exclude_ecology_lexical"
            exclusion_reason = (
                "The conservative ecological-content screen matched: "
                + ", ".join(screen_hits)
                + "."
            )
        elif manual_exclusion:
            disposition = "exclude_ecology_manual"
            exclusion_reason = manual_exclusion
        else:
            disposition = "eligible_non_ecological"
            exclusion_reason = None

        audit_row = {
            "disposition": disposition,
            "ecology_screen_hits": screen_hits,
            "exclusion_reason": exclusion_reason,
            "manual_ecology_review": manual_exclusion,
            "source_collection": row["source"],
            "source_id": row["id"],
            "source_index": source_index,
            "situation_sha256": sha256_text(situation),
            "title": row["title"],
            "topic": row["topic"],
            "word_count": word_count,
        }
        audit_rows.append(audit_row)
        if disposition == "eligible_non_ecological":
            eligible_rows.append(audit_row)

    length_candidates = [
        row for row in audit_rows if int(row["word_count"]) <= MAX_WORD_COUNT
    ]
    lexical_exclusions = [
        row
        for row in audit_rows
        if row["disposition"] == "exclude_ecology_lexical"
    ]
    manual_exclusions = [
        row
        for row in audit_rows
        if row["disposition"] == "exclude_ecology_manual"
    ]
    expected_counts = {
        "length candidates": (len(length_candidates), EXPECTED_LENGTH_CANDIDATES),
        "lexical exclusions": (
            len(lexical_exclusions),
            EXPECTED_LEXICAL_EXCLUSIONS,
        ),
        "manual exclusions": (len(manual_exclusions), EXPECTED_MANUAL_EXCLUSIONS),
        "non-ecological candidates": (
            len(eligible_rows),
            EXPECTED_NON_ECOLOGICAL_CANDIDATES,
        ),
    }
    mismatches = [
        f"{label}: {observed} != {expected}"
        for label, (observed, expected) in expected_counts.items()
        if observed != expected
    ]
    if mismatches:
        raise ValueError("Unexpected CLASH screening counts: " + "; ".join(mismatches))
    observed_manual_ids = {row["source_id"] for row in manual_exclusions}
    if observed_manual_ids != set(MANUAL_ECOLOGY_EXCLUSIONS):
        raise ValueError("Not every pinned manual ecology exclusion matched the source")

    # Taking the longest 98 is a transparent deterministic way to drop the three
    # short outliers and bring the mean close to the 233-word ecological corpus
    # while respecting the fixed candidate pool and 320-word ceiling.
    ranked = sorted(
        eligible_rows,
        key=lambda row: (-int(row["word_count"]), int(row["source_index"])),
    )
    selected = ranked[:TARGET_RELEASE_COUNT]
    selected_indices = {int(row["source_index"]) for row in selected}
    selection_ranks = {
        int(row["source_index"]): rank
        for rank, row in enumerate(ranked, start=1)
    }
    if len(selected_indices) != TARGET_RELEASE_COUNT:
        raise ValueError("CLASH selection did not produce 98 unique source rows")

    for audit_row in audit_rows:
        source_index = int(audit_row["source_index"])
        if audit_row["disposition"] != "eligible_non_ecological":
            audit_row["selection_rank"] = None
            continue
        audit_row["selection_rank"] = selection_ranks[source_index]
        if source_index in selected_indices:
            audit_row["disposition"] = "released"
        else:
            audit_row["disposition"] = "exclude_length_balance"
            audit_row["exclusion_reason"] = (
                "One of the three shortest non-ecological candidates; excluded "
                "to release exactly 98 examples and keep the mean close to the "
                "ecological prompt-only corpus."
            )

    records: list[dict[str, Any]] = []
    for source_index, row in enumerate(source_rows):
        if source_index not in selected_indices:
            continue
        situation = row["situation"]
        records.append(
            {
                "dilemma": situation,
                "id": f"clash-{row['id']}",
                "source": {
                    "collection": row["source"],
                    "dataset": DATASET_ID,
                    "file": SOURCE_FILENAME,
                    "revision": DATASET_REVISION,
                    "row_index": source_index,
                    "situation_sha256": sha256_text(situation),
                    "source_id": row["id"],
                    "topic": row["topic"],
                },
                "title": row["title"],
            }
        )
    if len(records) != TARGET_RELEASE_COUNT:
        raise ValueError(f"Expected 98 release records, found {len(records)}")

    output_dir.joinpath("README.md").write_text(RELEASE_README, encoding="utf-8")
    write_jsonl(output_dir / "audit.jsonl", audit_rows)
    write_jsonl(output_dir / "records.jsonl", records)

    released_audit = [row for row in audit_rows if row["disposition"] == "released"]
    manifest = {
        "artifacts": {
            filename: sha256_file(output_dir / filename)
            for filename in ("README.md", "audit.jsonl", "records.jsonl")
        },
        "candidate_count_at_or_below_max_words": len(length_candidates),
        "contains_actions": False,
        "contains_assistant_responses": False,
        "contains_character_perspectives": False,
        "contains_normative_labels": False,
        "contains_rationales": False,
        "dataset_type": "prompt_only",
        "excluded": {
            "above_max_words": sum(
                row["disposition"] == "exclude_length" for row in audit_rows
            ),
            "ecology_lexical": len(lexical_exclusions),
            "ecology_manual": len(manual_exclusions),
            "length_balance": sum(
                row["disposition"] == "exclude_length_balance"
                for row in audit_rows
            ),
        },
        "format_version": 1,
        "non_ecological_candidate_count": len(eligible_rows),
        "prompt_field": "dilemma",
        "released_count": len(records),
        "selection": {
            "max_word_count": MAX_WORD_COUNT,
            "method": (
                "Take the 98 longest rows after conservative lexical and manual "
                "ecological-content screening; break word-count ties by source row."
            ),
            "target_release_count": TARGET_RELEASE_COUNT,
            "word_count_convention": "len(situation.split())",
        },
        "source_collection_counts": describe_counts(
            released_audit, "source_collection"
        ),
        "source_dataset": {
            "dataset": DATASET_ID,
            "file": SOURCE_FILENAME,
            "revision": DATASET_REVISION,
            "row_count": EXPECTED_SOURCE_ROWS,
            "sha256": SOURCE_SHA256,
            "url": "https://huggingface.co/datasets/launch/CLASH",
        },
        "source_prompt_field": "situation",
        "topic_counts": describe_counts(released_audit, "topic"),
        "word_counts": word_statistics(released_audit),
    }
    write_json(output_dir / "manifest.json", manifest)
    return manifest


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    manifest = build(args.source, args.output_dir)
    print(
        f"Built {manifest['released_count']} CLASH prompt-only records at "
        f"{args.output_dir}"
    )


if __name__ == "__main__":
    main()
